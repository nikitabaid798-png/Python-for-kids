# Printing different variables and their data types

name = "Nikita"

age = 25

is_student = True

weight = 50.8

print("Name is:", name)
print("Data type of name is:", type(name))

print("\nAge is:", age)
print("Data type of age is:", type(age))

print("\nIs student:", is_student)
print("Data type of Student is:", type(is_student))

print("\nWeight is:", weight)
print("Data type of weight is:", type(weight))

# Applying Type Casting

print("\nAfter Type Casting...")

age = str(age)
print("\nAge is:", age)
print("Data type of age is:", type(age))

weight = int(weight)
print("\nWeight is:", weight)
print("Data type of weight is:", type(weight))
