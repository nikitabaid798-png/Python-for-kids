# Program to calculate the average speed of three cyclists

# Store the speeds of the three cyclists
cyclist1 = 10
cyclist2 = 20
cyclist3 = 30

# Calculate the average speed
average_speed = (cyclist1 + cyclist2 + cyclist3) / 3

# Display the average speed
print("Average speed:", average_speed, "km/h")

# Compare each cyclist's speed with the average
if cyclist1 < average_speed:
    print("Cyclist 1 is riding slower than the average speed.")

if cyclist2 < average_speed:
    print("Cyclist 2 is riding slower than the average speed.")

if cyclist3 < average_speed:
    print("Cyclist 3 is riding slower than the average speed.")
